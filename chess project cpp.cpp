int main() {
    cout << "Initializing... ";
    initialize();
    cout << "done\n";
    this_thread::sleep_for(chrono::milliseconds(500));
    string boardstate, castling, epsquare;
    cout << "FEN boardstate: ";
    cin >> boardstate;
    char split[boardstate.length()+1];
    strcpy(split, boardstate.c_str());
    int row = 0, square = 0, whiteKings = 0, blackKings = 0;
    for (char letter : split) {
        if (letter == '\0') continue;
        if (square > 8) {
            printRed("Invalid\n");
            return 0;
        }
        if (letter == '/') {
            if (square != 8) {
                printRed("Invalid\n");
                return 0;
            }
            square = 0;
            row++;
        } else if (isdigit(letter)) {
            square += (letter - 48);
        } else {
            if (letter == 'K') {whiteKings++;}
            if (letter == 'k') {blackKings++;}
            posBitboards[getPieceId(letter)] |= 1 << ((7 - row) * 8 + square);
            square++;
        }
    }
    if (whiteKings != 1 || blackKings != 1) {
        printRed("Invalid\n");
        return 0;
    }
    cout << "\nColor to move: ";
    cin >> toMove;
    cout << "\nCastling: ";
    cin >> castling;
    char split2[castling.length()+1];
    strcpy(split2, castling.c_str());
    for (char letter : split2) {
        switch (letter) {
            case 'K':
                wcs = true;
                break;
            case 'k':
                bcs = true;
                break;
            case 'Q':
                wcl = true;
                break;
            case 'q':
                bcl = true;
                break;
            default:
                break;
        }
    }
    cout << "\nEn passant square? ";
    cin >> epsquare;
    if (epsquare != "-") {ep = parseSquare(epsquare);}
    cout << "\nHalfmove timer: ";
    cin >> halfmove;
    currentZobrist = emptySeed ^ (toMove ? whiteToMove : blackToMove);
    if (wcs) {currentZobrist ^= zobristWCS;}
    if (wcl) {currentZobrist ^= zobristWCL;}
    if (bcs) {currentZobrist ^= zobristBCS;}
    if (bcl) {currentZobrist ^= zobristBCL;}
    for (int i = 0; i < 12; i++) {
        for (int square : unserialize(posBitboards[i])) {
            currentZobrist ^= zobrist[square][i];
        }
    }
    cout << endl;
    //check for openings
    cout << "Depth (number of full moves): ";
    cin << maxDepth;
    cout << endl;
    displayBoard();
    displayStats();
    if (maxDepth > 0) {
        for (int depth = 1; depth <= maxDepth; depth++) {
            cout << "Running at depth: " << depth << "\nCalculating...\n";
            auto start = chrono::steady_clock::now();
            array<int, 3> result = evalDepth(depth, -2147483648, 2147483647);
            auto end = chrono::steady_clock::now();
            auto timeTaken = chrono::duration_cast<chrono::nanoseconds>(end - start);
            auto nps = nodes * 1000000000 / timeTaken;
            auto secondsTaken = timeTaken / 1000000000;
            auto eval = result[0] / 10;
            if (result[0] == -2147483648 || result[0] == 2147483647) {
                cout << "\u001b[33m" << "Evaluation: " << eval << "\u001b[0m" << endl;
            } else {cout << "Evaluation: " << eval << endl;}
            cout << "Best move: " << parseSquareID(result[1]) << parseSquareID(result[2]) << endl;
            cout << "Nodes per second: " << nps << endl;
            cout << "in " << secondsTaken << " seconds" << endl;
            nodes = 0;
        }
    }
    return 0;
}
