vector<int> unserialize(uint64_t bitboard) {
    vector<int> output = {};
    while (bitboard != 0) {
        output.push_back(countr_zero(bitboard));
        bitboard &= (bitboard - 1);
    }
    return output;
}
uint64_t serialize(int squares[]) {
    uint64_t output = 0;
    for (int square : squares) {
        output |= (1 << square);
    }
    return output;
}
